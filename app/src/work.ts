// Pinboard `work task answer <askId> <option|text...>`. A lone
// leading number is a 1-based option (same numbering as --recommended), and
// anything after it is extra text; otherwise the whole thing is a free-text
// answer.
export function parseAnswerArgs(args: string[]): { askId: number; option?: number; text?: string } {
  const [rawId, ...words] = positionals(args);
  const askId = Number(rawId);
  if (!Number.isInteger(askId) || askId <= 0 || words.length === 0) throw new Error("task answer needs an ask id and an option number or text");
  const result: { askId: number; option?: number; text?: string } = { askId };
  if (/^\d+$/.test(words[0])) {
    const option = Number(words[0]);
    if (option < 1) throw new Error(`option numbers start at 1 (got ${words[0]})`);
    result.option = option - 1;
    words.shift();
  }
  const text = words.join(" ").trim();
  if (text) result.text = text;
  return result;
}

