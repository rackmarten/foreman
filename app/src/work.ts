// parseFlags only recognizes `--flag=value`, not a space-separated
// `--flag value` - the latter leaves flags[name] as the string "true"
// (parsed as a bare boolean flag), and a naive `Number(flags[name])` on
// that is NaN. That's harmless for a metrics field but not here: an
// attempt cap or timeout silently becoming NaN disables the safety limit
// entirely (`attempt >= NaN` is always false), rather than erroring - hit
// for real during I4a's own verification. Fail loud instead.
function numberFlag(flags: Record<string, string>, name: string, fallback: number): number {
  const raw = flags[name];
  if (raw === undefined) return fallback;
  const value = Number(raw);
  if (!Number.isFinite(value)) {
    throw new Error(`--${name} must be a number (got '${raw}') - use --${name}=<value>, not a space before the value`);
  }
  return value;
}

