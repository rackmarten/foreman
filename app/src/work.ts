// foreman has no UI of its own, so this is how the plan is read
// from the box that acts on it - the same `GET /plan/next` the dispatcher
// consults, printed rather than acted on.
async function planStatus(): Promise<void> {
  // one block per enabled license, because that is what the
  // dispatcher now asks - a single unscoped read showed pinboard's default
  // license only, which on a two-seat install is half the answer and silently
  // the wrong half for anything running on the other seat.
  const licenses = (await listLicenses()).filter((l) => l.enabled);
  const seats = licenses.length > 0 ? licenses : [{ id: undefined, name: "default" } as const];

  for (const seat of seats) {
    if (seats.length > 1) console.log(`== ${seat.name} ==`);
    const plan = await getPlanNext(seat.id);
    if (!plan.periodConfigured) {
      console.log("No budget period covers right now - set one on pinboard's Plan screen.");
      if (seats.length > 1) console.log("");
      continue;
    }
    console.log(`Period budget left: $${plan.periodRemainingUsd.toFixed(2)}`);
    // both caps, since either can be what's holding work back and
    // they have different remedies - raise this seat's limit vs. the global one.
    const caps =
      seats.length > 1 && plan.concurrency !== plan.concurrencyGlobal
        ? `concurrency ${plan.seatRunning}/${plan.concurrency} this seat, ${plan.concurrencyGlobal} across all`
        : `concurrency ${plan.concurrency}`;
    console.log(`Session window left: $${plan.sessionRemainingUsd.toFixed(2)} (${caps})`);
    if (plan.tasks.length === 0) {
      console.log(`Nothing may start: ${plan.reason ?? "no reason given"}`);
      if (plan.waitUntil) console.log(`Session window resets at ${plan.waitUntil}`);
    } else {
      console.log(`May start now (${plan.tasks.length}):`);
      for (const t of plan.tasks) {
        console.log(`  #${t.taskId} p${t.priority} ~$${t.estimatedCostUsd.toFixed(2)} (${t.estimateBasis})  ${t.title}`);
      }
    }
    if (seats.length > 1) console.log("");
  }
}

