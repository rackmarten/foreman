function renderPlanMarkdown(
  project: { slug: string; name: string },
  openTasks: Task[],
  current: Task | undefined,
  latestHandoff: Awaited<ReturnType<typeof getProjectHandoffs>>[number] | undefined,
): string {
  const lines: string[] = [PLAN_MARKER, "", `# ${project.name} plan`, ""];
  lines.push(`Full backlog and history: pinboard, project \`${project.slug}\`.`, "");
  lines.push("## Current", "");
  lines.push(current ? formatTaskLine(current) : "No open tasks.", "");
  lines.push("## Open tasks", "");
  if (openTasks.length === 0) {
    lines.push("None.");
  } else {
    for (const task of openTasks) lines.push(`- ${formatTaskLine(task)}`);
  }
  lines.push("", "## Latest handoff", "");
  if (latestHandoff) {
    lines.push(`Task: ${latestHandoff.taskTitle} (#${latestHandoff.taskId})`, "");
    const fields: [string, string | null][] = [
      ["Completed", latestHandoff.completed],
      ["Changed", latestHandoff.changed],
      ["Verified", latestHandoff.verified],
      ["Problems", latestHandoff.problems],
      ["Discovered", latestHandoff.discovered],
      ["Next", latestHandoff.next],
    ];
    for (const [label, value] of fields) {
      if (value) lines.push(`**${label}:** ${value}`, "");
    }
  } else {
    lines.push("None recorded yet.", "");
  }
  lines.push("---", `Generated ${new Date().toISOString()} by \`work plan sync\`.`, "");
  return lines.join("\n");
}

async function planSync(args: string[]): Promise<void> {
  const slug = positionals(args)[0];
  const flags = parseFlags(args);
  if (!slug) {
    usage();
    process.exit(2);
  }
  const projects = await listProjects();
  const project = projects.find((p) => p.slug === slug);
  if (!project) throw new Error(`no project with slug '${slug}'`);
  if (!project.localPath) throw new Error(`project '${slug}' has no localPath set`);

  const targetPath = join(WORKSPACE_ROOT, project.localPath, "PLAN.md");
  if (existsSync(targetPath) && flags.force !== "true") {
    const existing = readFileSync(targetPath, "utf8");
    if (!existing.startsWith(PLAN_MARKER)) {
      throw new Error(
        `${targetPath} already exists and isn't a generated PLAN.md (no marker comment) - ` +
          `refusing to overwrite a hand-written plan. Pass --force to overwrite anyway.`,
      );
    }
  }

  const tasks = await listTasks({ projectId: project.id });
  const openTasks = tasks.filter((t) => t.status !== "done");
  const current =
    openTasks.find((t) => t.status === "executing" || t.status === "handoff") ?? openTasks[0];
  const handoffs = await getProjectHandoffs(project.id, 1);

  writeFileSync(targetPath, renderPlanMarkdown(project, openTasks, current, handoffs[0]));
  console.log(`Wrote ${targetPath}`);
}

