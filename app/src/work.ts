// `work task ask`'s structured flags. No --option at all is a
// free-text question; otherwise 2-4 options, each `<label>|<rationale>`
// (the rationale is optional), and --recommended naming one of them.
export function parseAskArgs(args: string[]): { id: number; question: string; structure: AskStructure } {
  const id = Number(args[0]);
  const question = positionals(args).slice(1).join(" ").trim();
  if (!Number.isInteger(id) || id <= 0 || !question) throw new Error("task ask needs a task id and a question");
  const flags = parseFlags(args.slice(1));
  const options = repeatedFlag(args, "option").map((raw) => {
    const sep = raw.indexOf("|");
    const label = (sep < 0 ? raw : raw.slice(0, sep)).trim();
    const rationale = sep < 0 ? "" : raw.slice(sep + 1).trim();
    if (!label) throw new Error(`--option needs a label (got '${raw}')`);
    return rationale ? { label, rationale } : { label };
  });
  const structure: AskStructure = { options };
  if (flags.context?.trim()) structure.context = flags.context.trim();
  if (options.length === 0) {
    if (flags.recommended !== undefined) throw new Error("--recommended needs --option flags");
    return { id, question, structure };
  }
  if (options.length < 2 || options.length > 4) throw new Error(`a structured ask needs 2-4 --option flags (got ${options.length})`);
  const recommended = Number(flags.recommended);
  if (!Number.isInteger(recommended) || recommended < 1 || recommended > options.length) {
    throw new Error(`--recommended must be an option number from 1 to ${options.length} (got '${flags.recommended ?? ""}')`);
  }
  structure.recommended = recommended - 1;
  return { id, question, structure };
}

