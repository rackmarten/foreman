async function main(): Promise<void> {
  const [group, action, ...rest] = process.argv.slice(2);

  if (group === "root") {
    process.exitCode = await runRoot(
      [action, ...rest].filter((a): a is string => a !== undefined),
      process.env,
      process.cwd(),
      defaultRootDeps,
    );
    return;
  }
  if (group === "plan" && action === "sync") return planSync(rest);
  if (group === "usage" && action === "observe") return usageObserve(rest);
  if (group === "usage" && action === "status") return usageStatus();
  if (group === "pipeline" && action === "poll") return pipelinePoll();
  if (group === "pipeline" && action === "watch") return pipelineWatch(rest);
  if (group === "releases" && action === "probe") {
    const { probed, failed } = await probeAll();
    console.log(`releases: probed ${probed} project(s)${failed ? `, ${failed} failed` : ""}`);
    return;
  }
  if (group === "releases" && action === "deploy-next") {
    console.log(`releases: ${(await runNextDeployRequest()) ?? "no queued deploy request"}`);
    return;
  }
  if (group === "chat" && action === "poll") return chatPoll();
  if (group === "chat" && action === "watch") return chatWatch(rest);
  if (group === "chat" && action === "daemon") return chatDaemon();
  if (group === "plan" && action === "status") return planStatus();
    if (group === "dispatch") return dispatch([action, ...rest].filter((a): a is string => a !== undefined));

  if (group !== "task" || !action) {
    usage();
    process.exit(group === undefined ? 0 : 2);
  }

  switch (action) {
    case "list":
      return taskList(rest);
    case "show":
      return taskShow(rest);
    case "next":
      return taskNext();
    case "create":
      return taskCreate(rest);
    case "update":
      return taskUpdate(rest);
    case "label":
      return taskLabel(rest);
    case "relate":
      return taskRelate(rest);
    case "add-related-repo":
      return taskAddRelatedRepo(rest);
    case "claim":
      return taskClaim(rest);
    case "comment":
      return taskComment(rest);
    case "handoff":
      return taskHandoff(rest);
    case "run":
      return taskRun(rest);
    case "complete":
      return taskComplete(rest);
    case "ask":
      return taskAsk(rest);
    case "answer":
      return taskAnswer(rest);
    case "assume":
      return taskAssume(rest);
    default:
      usage();
      process.exit(2);
  }
}

// Only run the CLI when this file is executed directly, not when it's
// imported (e.g. by work.test.ts) - otherwise import side effects would
// call process.exit() before the importer gets to do anything. Compares
// realpaths rather than raw argv[1], since `npm link` invokes this file
// through a symlink (e.g. ~/.local-node/bin/work): import.meta.url always
// resolves to this file's real path, but process.argv[1] keeps the
// symlink path as invoked, so a direct string comparison never matches
// and main() silently never runs.
const isMainModule =
  process.argv[1] !== undefined && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMainModule) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  });
}
